function normalizeWord(word: string): string {
    return word
        .toLowerCase()
        .replace(/[łŁ]/g, "l")
        .normalize("NFKD")
        .replace(/[\u0300-\u036f]/g, "")
        .trim();
}

const normalizedPolish = RAW_POLISH_STOPWORDS.flatMap((w) => [
    w.toLowerCase(),
    normalizeWord(w),
]);

export const GLOBAL_STOPWORDS: Set<string> = new Set([
    ...english,
    ...spanish,
    ...german,
    ...french,
    ...italian,
    ...portuguese,
    ...russian,
    ...ukrainian,
    ...arabic,
    ...dutch,
    ...normalizedPolish,
]);

export function isStopword(token: string): boolean {
    return (
        GLOBAL_STOPWORDS.has(token) ||
        GLOBAL_STOPWORDS.has(normalizeWord(token))
    );
}
